uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.07 0.435 0.41 0.06], ...
    'String', 'Remove selected', ...
    'Callback', @removePlanckTemperature);

uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.52 0.435 0.41 0.06], ...
    'String', 'Reset', ...
    'Callback', @resetPlanckTemperatures);

visibleBandCheck = uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'checkbox', ...
    'Units', 'normalized', ...
    'Position', [0.07 0.35 0.86 0.06], ...
    'String', 'Shade visible range (380-750 nm)', ...
    'Value', 1, ...
    'BackgroundColor', 'w', ...
    'Callback', @(~,~) updatePlanckPlot());

uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.07 0.08 0.86 0.23], ...
    'String', { ...
        'Validation:', ...
        'The numerical maximum of each', ...
        'calculated spectrum is compared', ...
        'with Wien''s law:', ...
        'lambda_max T = b.'}, ...
    'HorizontalAlignment', 'left', ...
    'BackgroundColor', 'w');


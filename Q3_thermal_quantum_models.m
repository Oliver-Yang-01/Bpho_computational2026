    'Parent', planckTab, ...
    'Units', 'normalized', ...
    'Position', [0.07 0.30 0.66 0.64]);

planckTable = uitable( ...
    'Parent', planckTab, ...
    'Units', 'normalized', ...
    'Position', [0.07 0.055 0.66 0.18], ...
    'ColumnName', {'T / K', 'Numerical peak / nm', ...
                   'Wien peak / nm', 'Difference / %'}, ...
    'ColumnEditable', false(1,4), ...
    'RowName', []);

planckPanel = uipanel( ...
    'Parent', planckTab, ...
    'Units', 'normalized', ...
    'Position', [0.76 0.055 0.22 0.885], ...
    'Title', 'Temperatures and display', ...
    'FontWeight', 'bold', ...
    'BackgroundColor', 'w');

uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.07 0.91 0.86 0.05], ...
    'String', 'Temperatures currently plotted:', ...
    'HorizontalAlignment', 'left', ...
    'BackgroundColor', 'w');

planckList = uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'listbox', ...
    'Units', 'normalized', ...
    'Position', [0.07 0.64 0.86 0.27], ...
    'Min', 0, ...
    'Max', 20, ...
    'Value', 1);

uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'text', ...
    'Units', 'normalized', ...
    'Position', [0.07 0.565 0.86 0.05], ...
    'String', 'Add a temperature (K):', ...
    'HorizontalAlignment', 'left', ...
    'BackgroundColor', 'w');

planckTemperatureEdit = uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'edit', ...
    'Units', 'normalized', ...
    'Position', [0.07 0.515 0.52 0.055], ...
    'String', '4500', ...
    'BackgroundColor', 'w');

uicontrol( ...
    'Parent', planckPanel, ...
    'Style', 'pushbutton', ...
    'Units', 'normalized', ...
    'Position', [0.62 0.515 0.31 0.055], ...
    'String', 'Add', ...

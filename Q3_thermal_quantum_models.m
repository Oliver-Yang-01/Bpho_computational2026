function task03_thermal_quantum_models()
% TASK03_THERMAL_QUANTUM_MODELS
% BPhO Computational Physics Challenge 2026 - Task 3
%
% Interactive comparison of:
%   1) Planck's black-body radiation law
%   2) Einstein's model of molar heat capacity
%
% The program combines the clear plots from BBRbasic.m with the interactive
% tabbed layout from BlackBodyRadiation.m, while correcting the legend,
% units, peak calculation and numerical stability.
%
% Run from the Command Window with:
%   task03_thermal_quantum_models

close all;
clc;

%% Physical constants (exact SI values where defined)
h      = 6.62607015e-34;       % Planck constant / J s
c      = 299792458;            % Speed of light / m s^-1
kB     = 1.380649e-23;         % Boltzmann constant / J K^-1
R      = 8.31446261815324;      % Molar gas constant / J mol^-1 K^-1
bWien  = 2.897771955e-3;        % Wien displacement constant / m K

%% Default data
planckTemperatures = [3000 4000 5000 6000];

% Einstein temperatures in kelvin.
% Au, Cu and Fe retain the values used in the original challenge drafts.
% The additional values are representative comparison values; the array is
% deliberately placed here so they can easily be replaced by values from a
% preferred reference source.
materialNames = { ...
    'Gold (Au)', ...
    'Copper (Cu)', ...
    'Iron (Fe)', ...
    'Silver (Ag)', ...
    'Aluminium (Al)', ...
    'Lead (Pb)', ...
    'Tungsten (W)', ...
    'Nickel (Ni)'};

thetaEinstein = [165 230 430 225 300 105 400 450];

%% Main window
fig = figure( ...
    'Name', 'Task 3: Thermal Quantum Models', ...
    'NumberTitle', 'off', ...
    'Color', 'w', ...
    'Position', [80 80 1260 740], ...
    'Resize', 'on');

mainTabs = uitabgroup('Parent', fig);
planckTab = uitab('Parent', mainTabs, 'Title', 'Planck spectrum');
einsteinTab = uitab('Parent', mainTabs, 'Title', 'Einstein heat capacity');

%% ========================================================================
% TAB 1: PLANCK BLACK-BODY RADIATION
% =========================================================================

%% ========================================================================
% NESTED CALLBACK AND CALCULATION FUNCTIONS
% =========================================================================
    function updatePlanckList()
        labels = arrayfun(@(T) sprintf('%.0f K', T), ...
            planckTemperatures, 'UniformOutput', false);
        set(planckList, 'String', labels);

        currentValue = get(planckList, 'Value');
        if isempty(labels)
            set(planckList, 'Value', []);
        else
            currentValue = currentValue(currentValue <= numel(labels));
            if isempty(currentValue)
                currentValue = 1;
            end
            set(planckList, 'Value', currentValue);
        end
    end

    function addPlanckTemperature(~,~)
        newTemperature = str2double(get(planckTemperatureEdit, 'String'));

        if ~isfinite(newTemperature) || newTemperature < 500 || ...
                newTemperature > 20000
            errordlg(['Enter a temperature between 500 K and 20000 K. ' ...
                      'This range keeps the selected wavelength window useful.'], ...
                     'Invalid temperature');
            return;
        end

        if any(abs(planckTemperatures - newTemperature) < 1e-9)
            errordlg('That temperature is already plotted.', ...
                     'Duplicate temperature');
            return;
        end

        planckTemperatures(end+1) = newTemperature;
        planckTemperatures = sort(planckTemperatures);
        updatePlanckList();
        updatePlanckPlot();
    end

    function removePlanckTemperature(~,~)
        selected = get(planckList, 'Value');
        if isempty(selected)
            return;
        end

        if numel(selected) >= numel(planckTemperatures)
            errordlg('At least one temperature must remain.', ...
                     'Cannot remove all curves');
            return;
        end

        planckTemperatures(selected) = [];
        set(planckList, 'Value', 1);
        updatePlanckList();
        updatePlanckPlot();
    end

    function resetPlanckTemperatures(~,~)
        planckTemperatures = [3000 4000 5000 6000];
        set(planckList, 'Value', 1);
        updatePlanckList();
        updatePlanckPlot();
    end

    function updatePlanckPlot()
        cla(planckAxes);
        hold(planckAxes, 'on');

        % Plot in nm, but evaluate Planck's law using metres.
        lambdaNm = linspace(100, 3000, 3500);
        lambdaM = lambdaNm * 1e-9;

        numberOfCurves = numel(planckTemperatures);
        curveColours = lines(max(numberOfCurves, 1));
        lineHandles = gobjects(numberOfCurves, 1);
        resultData = zeros(numberOfCurves, 4);

        maximumRadiance = 0;
        radianceCurves = cell(numberOfCurves, 1);

        for index = 1:numberOfCurves
            temperature = planckTemperatures(index);
            spectralRadiance = planckPerNanometre(lambdaM, temperature);
            radianceCurves{index} = spectralRadiance;
            maximumRadiance = max(maximumRadiance, max(spectralRadiance));
        end

        if get(visibleBandCheck, 'Value') == 1 && maximumRadiance > 0
            visiblePatch = patch(planckAxes, ...
                [380 750 750 380], ...
                [0 0 1.08*maximumRadiance 1.08*maximumRadiance], ...
                [0.75 0.75 0.75], ...
                'FaceAlpha', 0.16, ...
                'EdgeColor', 'none', ...
                'HandleVisibility', 'off');
            uistack(visiblePatch, 'bottom');
            text(planckAxes, 565, 1.045*maximumRadiance, ...
                'Visible spectrum', ...
                'HorizontalAlignment', 'center', ...
                'Color', [0.35 0.35 0.35], ...
                'FontSize', 9, ...
                'HandleVisibility', 'off');
        end

        for index = 1:numberOfCurves
            temperature = planckTemperatures(index);
            spectralRadiance = radianceCurves{index};

            lineHandles(index) = plot(planckAxes, lambdaNm, spectralRadiance, ...
                'LineWidth', 2.2, ...
                'Color', curveColours(index,:), ...
                'DisplayName', sprintf('%.0f K', temperature));

            % Numerical peak from the calculated Planck curve.
            [numericalPeakRadiance, peakIndex] = max(spectralRadiance);
            numericalPeakNm = lambdaNm(peakIndex);

            % Independent theoretical prediction from Wien's displacement law.
            wienPeakNm = (bWien / temperature) * 1e9;
            percentageDifference = ...
                100 * abs(numericalPeakNm - wienPeakNm) / wienPeakNm;

            plot(planckAxes, numericalPeakNm, numericalPeakRadiance, 'o', ...
                'Color', curveColours(index,:), ...
                'MarkerFaceColor', curveColours(index,:), ...
                'MarkerSize', 6, ...
                'HandleVisibility', 'off');

            resultData(index,:) = [temperature, numericalPeakNm, ...
                                   wienPeakNm, percentageDifference];
        end

        hold(planckAxes, 'off');
        grid(planckAxes, 'on');
        box(planckAxes, 'on');
        xlim(planckAxes, [100 3000]);
        if maximumRadiance > 0
            ylim(planckAxes, [0 1.08*maximumRadiance]);
        end

        xlabel(planckAxes, 'Wavelength, \lambda (nm)');
        ylabel(planckAxes, ...
            'Spectral radiance, B_\lambda (W m^{-2} sr^{-1} nm^{-1})');
        title(planckAxes, 'Planck Black-Body Radiation Spectrum');
        legend(planckAxes, lineHandles, 'Location', 'northeast');

        set(planckTable, 'Data', resultData);
        drawnow;
    end

    function spectralRadianceNm = planckPerNanometre(lambdaMetres, temperature)
        % Planck spectral radiance per unit wavelength.
        % SI form initially gives W m^-3 sr^-1. Multiplication by 1e-9
        % converts it to W m^-2 sr^-1 nm^-1 for a nanometre x-axis.
        exponent = h*c ./ (lambdaMetres*kB*temperature);

        spectralRadiancePerMetre = zeros(size(lambdaMetres));
        safe = exponent < 700;
        spectralRadiancePerMetre(safe) = ...
            (2*h*c^2 ./ lambdaMetres(safe).^5) ./ expm1(exponent(safe));

        spectralRadianceNm = spectralRadiancePerMetre * 1e-9;
    end

    function labels = makeMaterialLabels()
        labels = cell(size(materialNames));
        for index = 1:numel(materialNames)
            labels{index} = sprintf('%s   (theta_E = %.0f K)', ...
                materialNames{index}, thetaEinstein(index));
        end
    end

    function selectDefaultMaterials(~,~)
        set(materialList, 'Value', 1:3);
        updateEinsteinPlot();
    end

    function updateEinsteinPlot()
        selectedMaterials = get(materialList, 'Value');
        maximumTemperature = str2double(get(maximumTemperatureEdit, 'String'));

        if ~isfinite(maximumTemperature) || maximumTemperature < 100 || ...
                maximumTemperature > 5000
            errordlg('Enter a maximum temperature between 100 K and 5000 K.', ...
                     'Invalid temperature range');
            set(maximumTemperatureEdit, 'String', '800');
            return;
        end

        if isempty(selectedMaterials)
            errordlg('Select at least one material.', 'No material selected');
            set(materialList, 'Value', 1:3);
            selectedMaterials = 1:3;
        end

        temperatureVector = linspace(1, maximumTemperature, 1200);
        curveColours = lines(numel(selectedMaterials));

        cla(einsteinAxes);
        hold(einsteinAxes, 'on');
        lineHandles = gobjects(numel(selectedMaterials), 1);

        for plotIndex = 1:numel(selectedMaterials)
            materialIndex = selectedMaterials(plotIndex);
            thetaE = thetaEinstein(materialIndex);
            x = thetaE ./ temperatureVector;

            % Stable version of the Einstein heat-capacity expression:
            % Cv = 3R x^2 exp(x) / (exp(x)-1)^2
            %    = 3R x^2 exp(-x) / (1-exp(-x))^2
            denominator = -expm1(-x);
            heatCapacity = 3*R .* x.^2 .* exp(-x) ./ denominator.^2;

            lineHandles(plotIndex) = plot(einsteinAxes, ...
                temperatureVector, heatCapacity, ...
                'LineWidth', 2.2, ...
                'Color', curveColours(plotIndex,:), ...
                'DisplayName', materialNames{materialIndex});
        end

        dulongPetit = 3*R;
        yline(einsteinAxes, dulongPetit, '--', ...
            sprintf('Dulong-Petit limit: 3R = %.2f J mol^{-1} K^{-1}', ...
                    dulongPetit), ...
            'LineWidth', 1.4, ...
            'LabelHorizontalAlignment', 'left', ...
            'HandleVisibility', 'off');

        hold(einsteinAxes, 'off');
        grid(einsteinAxes, 'on');
        box(einsteinAxes, 'on');
        xlim(einsteinAxes, [0 maximumTemperature]);
        ylim(einsteinAxes, [0 1.05*dulongPetit]);

        xlabel(einsteinAxes, 'Temperature, T (K)');
        ylabel(einsteinAxes, 'Molar heat capacity, C_V (J mol^{-1} K^{-1})');
        title(einsteinAxes, 'Einstein Model of Molar Heat Capacity');
        legend(einsteinAxes, lineHandles, 'Location', 'southeast');
        drawnow;
    end
end

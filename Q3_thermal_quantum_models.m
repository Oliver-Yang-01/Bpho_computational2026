    'String', { ...
        'The dashed line is 3R, the', ...
        'Dulong-Petit high-temperature', ...
        'limit. Different Einstein', ...
        'temperatures control how rapidly', ...
        'each crystal approaches 3R.'}, ...
    'HorizontalAlignment', 'left', ...
    'BackgroundColor', 'w');

